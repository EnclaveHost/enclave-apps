json service_once(const json &request) {
  const auto bytes = request.dump();
  if (bytes.size() > (8 << 20))
    throw std::runtime_error("request limit");
  Fd socket_fd(socket(AF_UNIX, SOCK_STREAM | SOCK_CLOEXEC, 0));
  if (socket_fd.value < 0)
    throw std::runtime_error("socket failed");
  timeval timeout{1200, 0};
  setsockopt(socket_fd.value, SOL_SOCKET, SO_RCVTIMEO, &timeout,
             sizeof(timeout));
  setsockopt(socket_fd.value, SOL_SOCKET, SO_SNDTIMEO, &timeout,
             sizeof(timeout));
  sockaddr_un addr{};
  addr.sun_family = AF_UNIX;
  std::strcpy(addr.sun_path, "/run/shield/compute.sock");
  if (connect(socket_fd.value, reinterpret_cast<sockaddr *>(&addr),
              sizeof(addr))) {
    // A full Unix listen backlog is pre-connection admission contention. No
    // request or protected transaction has begun, so the bounded busy retry
    // is safe. Other connection failures must not be retried as computations.
    if(errno==EAGAIN) return {{"ok",false},{"error","compute busy"}};
    throw std::runtime_error("Shield service unavailable");
  }
  uint32_t size = htonl(bytes.size());
  // send(MSG_NOSIGNAL) prevents a retired service from terminating the app.
  std::string packet(reinterpret_cast<char *>(&size), sizeof(size));
  packet += bytes;
  size_t offset = 0;
  while (offset < packet.size()) {
    auto n = send(socket_fd.value, packet.data() + offset,
                  packet.size() - offset, MSG_NOSIGNAL);
    if (n < 0 && errno == EINTR)
      continue;
    if (n <= 0)
      throw std::runtime_error("Shield send failed");
    offset += n;
  }
  read_all(socket_fd.value, &size, sizeof(size));
  size = ntohl(size);
  if (!size || size > (16 << 20))
    throw std::runtime_error("response limit");
  std::string response(size, '\0');
  read_all(socket_fd.value, response.data(), size);
  auto result = json::parse(response);
  return result;
}
json service(const json &request) {
  const auto deadline =
      std::chrono::steady_clock::now() + std::chrono::minutes(20);
  while (true) {
    auto result = service_once(request);
    if (result.value("ok", false))
      return result;
    // Only admission contention is retryable. Execution/integrity errors
    // cannot silently select another route or issue a second computation.
    if (result.value("error", "") != "compute busy" ||
        std::chrono::steady_clock::now() >= deadline)
      throw std::runtime_error("Shield computation refused");
    std::this_thread::sleep_for(std::chrono::milliseconds(100));
  }
}
struct Job {
  std::shared_ptr<Profile> profile;
  cl_command_queue private_queue = nullptr;
  cl_event ready = nullptr, completion = nullptr;
  std::array<cl_mem, 3> buffers{};
  std::array<void *, 3> svm_pointers{};
  std::array<std::shared_ptr<SvmAllocation>, 3> svm_storage;
  cl_uint m = 0, n = 0, k = 0;
  ~Job() {
    for (auto b : buffers)
      if (b)
        REAL(clReleaseMemObject)(b);
    if (ready)
      REAL(clReleaseEvent)(ready);
    if (completion)
      REAL(clReleaseEvent)(completion);
    if (private_queue)
      REAL(clReleaseCommandQueue)(private_queue);
  }
  void execute() {
    cl_int result = CL_EXEC_STATUS_ERROR_FOR_EVENTS_IN_WAIT_LIST;
    try {
      if (REAL(clWaitForEvents)(1, &ready))
        throw std::runtime_error("dependency failed");
      const bool timed = profile && profile->sample(profile->started);
      std::vector<int8_t> a(size_t(m) * k), b(size_t(k) * n);
      auto read = [&](unsigned i, void *out, size_t bytes) {
        if (svm_storage[i])
          return REAL(clEnqueueSVMMemcpy)(private_queue, CL_TRUE, out,
                                          svm_pointers[i], bytes, 0, nullptr, nullptr);
        return REAL(clEnqueueReadBuffer)(private_queue, buffers[i], CL_TRUE, 0,
                                          bytes, out, 0, nullptr, nullptr);
      };
      if (read(0, a.data(), a.size()) || read(1, b.data(), b.size()))
        throw std::runtime_error("input read failed");
      json av = json::array(), bv = json::array();
      for (size_t i = 0; i < m; i++) {
        json row = json::array();
        for (size_t j = 0; j < k; j++)
          row.push_back(int(a[i * k + j]));
        av.push_back(std::move(row));
      }
      for (size_t i = 0; i < k; i++) {
        json row = json::array();
        for (size_t j = 0; j < n; j++)
          row.push_back(int(b[i * n + j]));
        bv.push_back(std::move(row));
      }
      json graph = {{"schema", "shield-graph/1"},
                    {"nodes", json::array({{{"name", "a"},
                                            {"op", "input"},
                                            {"shape", {m, k}},
                                            {"bound", 128}},
                                           {{"name", "b"},
                                            {"op", "constant"},
                                            {"shape", {k, n}},
                                            {"value", std::move(bv)}},
                                           {{"name", "c"},
                                            {"op", "matmul"},
                                            {"args", {"a", "b"}}}})},
                    {"outputs", {"c"}}};
      auto response = service({{"op", "graph"},
                               {"mode", "masked"},
                               {"graph", std::move(graph)},
                               {"inputs", {{"a", std::move(av)}}}});
      const auto &rows = response.at("outputs").at("c");
      if (!rows.is_array() || rows.size() != m)
        throw std::runtime_error("output shape");
      std::vector<cl_long> output;
      output.reserve(size_t(m) * n);
      for (const auto &row : rows) {
        if (!row.is_array() || row.size() != n)
          throw std::runtime_error("output shape");
        for (const auto &x : row) {
          if (!x.is_number_integer())
            throw std::runtime_error("output type");
          if (x.is_number_unsigned() &&
              x.get<uint64_t>() > uint64_t(std::numeric_limits<int64_t>::max()))
            throw std::runtime_error("output integer overflow");
          auto v = x.get<int64_t>();
          if (v < -int64_t(16384) * k || v > int64_t(16384) * k)
            throw std::runtime_error("output range");
          output.push_back(v);
        }
      }
      // No output buffer is modified before the trusted service returns
      // success.
      const size_t output_bytes = output.size() * sizeof(cl_long);
      cl_int written = svm_storage[2]
          ? REAL(clEnqueueSVMMemcpy)(private_queue, CL_TRUE, svm_pointers[2],
                                      output.data(), output_bytes, 0, nullptr, nullptr)
          : REAL(clEnqueueWriteBuffer)(private_queue, buffers[2], CL_TRUE, 0,
                                        output_bytes, output.data(), 0, nullptr, nullptr);
      if (written)
        throw std::runtime_error("output write failed");
      if (timed && profile->sample(profile->ended) &&
          profile->queued <= profile->submitted &&
          profile->submitted <= profile->started &&
          profile->started <= profile->ended)
        profile->recorded.store(true, std::memory_order_release);
      result = CL_COMPLETE;
    } catch (...) { /* Execution failure is visible through the event; never
                       retry raw. */
    }
    REAL(clSetUserEventStatus)(completion, result);
    active_jobs.fetch_sub(1);
  }
};
struct Storage {
  cl_mem root;
  size_t offset, size;
  cl_context context;
  cl_mem_flags flags;
};
bool storage(cl_mem b, Storage &out) {
  out = {b, 0, 0, nullptr, 0};
  if (!b)
    return false;
  cl_mem_object_type type;
  if (REAL(clGetMemObjectInfo)(b, CL_MEM_TYPE, sizeof(type), &type, nullptr) ||
      type != CL_MEM_OBJECT_BUFFER)
    return false;
  if (REAL(clGetMemObjectInfo)(b, CL_MEM_SIZE, sizeof(out.size), &out.size,
                               nullptr) ||
      REAL(clGetMemObjectInfo)(b, CL_MEM_CONTEXT, sizeof(out.context),
                               &out.context, nullptr) ||
      REAL(clGetMemObjectInfo)(b, CL_MEM_FLAGS, sizeof(out.flags), &out.flags,
                               nullptr))
    return false;
  // OpenCL sub-buffers have only one parent level. Check every backing range.
  cl_mem parent = nullptr;
  if (REAL(clGetMemObjectInfo)(b, CL_MEM_ASSOCIATED_MEMOBJECT, sizeof(parent),
                               &parent, nullptr))
    return false;
  if (parent) {
    out.root = parent;
    if (REAL(clGetMemObjectInfo)(b, CL_MEM_OFFSET, sizeof(out.offset),
                                 &out.offset, nullptr))
      return false;
  }
  return true;
}
