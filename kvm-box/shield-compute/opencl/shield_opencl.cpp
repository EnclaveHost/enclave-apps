struct Fd {
  int value = -1;
  explicit Fd(int n = -1) : value(n) {}
  ~Fd() {
    if (value >= 0)
      close(value);
  }
  Fd(const Fd &) = delete;
};
void write_all(int fd, const void *ptr, size_t n) {
  const auto *p = static_cast<const char *>(ptr);
  while (n) {
    ssize_t r = write(fd, p, n);
    if (r < 0 && errno == EINTR)
      continue;
    if (r <= 0)
      throw std::runtime_error("write failed");
    p += r;
    n -= r;
  }
}
void read_all(int fd, void *ptr, size_t n) {
  auto *p = static_cast<char *>(ptr);
  while (n) {
    ssize_t r = read(fd, p, n);
    if (r < 0 && errno == EINTR)
      continue;
    if (r <= 0)
      throw std::runtime_error("read failed");
    p += r;
    n -= r;
  }
}
json invoke_compiler(const json &description) {
  // Files are unlinked immediately; source never leaves this VM process
  // boundary.
  char in_name[] = "/tmp/shield-cl-in-XXXXXX",
       out_name[] = "/tmp/shield-cl-out-XXXXXX";
  Fd input(mkstemp(in_name));
  if (input.value < 0)
    return json::object();
  unlink(in_name);
  Fd output(mkstemp(out_name));
  if (output.value < 0)
    return json::object();
  unlink(out_name);
  fcntl(input.value, F_SETFD, FD_CLOEXEC);
  fcntl(output.value, F_SETFD, FD_CLOEXEC);
  auto request = description.dump();
  write_all(input.value, request.data(), request.size());
  lseek(input.value, 0, SEEK_SET);
  posix_spawn_file_actions_t actions;
  posix_spawn_file_actions_init(&actions);
  posix_spawn_file_actions_adddup2(&actions, input.value, STDIN_FILENO);
  posix_spawn_file_actions_adddup2(&actions, output.value, STDOUT_FILENO);
  posix_spawn_file_actions_addopen(&actions, STDERR_FILENO, "/dev/null",
                                   O_WRONLY, 0);
  const char *argv[] = {"python3", "-I", SHIELD_COMPILER, nullptr};
  pid_t pid;
  int error = posix_spawn(&pid, "/usr/bin/python3", &actions, nullptr,
                          const_cast<char **>(argv), environ);
  posix_spawn_file_actions_destroy(&actions);
  if (error)
    return json::object();
  int status;
  while (waitpid(pid, &status, 0) < 0) {
    if (errno != EINTR)
      return json::object();
  }
  if (!WIFEXITED(status) || WEXITSTATUS(status) != 0)
    return json::object();
  auto length = lseek(output.value, 0, SEEK_END);
  if (length < 0 || length > 65536)
    return json::object();
  lseek(output.value, 0, SEEK_SET);
  std::string result(length, '\0');
  read_all(output.value, result.data(), result.size());
  return json::parse(result);
}
json selected_plan(const json &plans, const char *name) {
  if (!plans.is_object() || !plans.contains(name) || !plans[name].is_object())
    return json::object();
  return plans[name];
}
bool integer_dispatch_plan(const json &plan) {
  // Analysis-only and future operation plans must not become executable just
  // because their kernel name is present in a source or program cache.
  return plan.is_object() && plan.value("operation", "") == "gemm-i8-i8-i64" &&
         plan.value("dispatchable", true);
}
