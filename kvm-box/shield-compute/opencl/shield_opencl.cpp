template <class T> T real(const char *name) {
  auto p = dlsym(RTLD_NEXT, name);
  if (!p)
    throw std::runtime_error("missing OpenCL entry point");
  return reinterpret_cast<T>(p);
}
#define REAL(name) real<decltype(&name)>(#name)
cl_int copy_info(const void *value, size_t bytes, size_t size, void *out,
                 size_t *actual) {
  if (actual)
    *actual = bytes;
  if (out) {
    if (size < bytes)
      return CL_INVALID_VALUE;
    std::memcpy(out, value, bytes);
  }
  return CL_SUCCESS;
}
cl_int text_info(const char *value, size_t size, void *out, size_t *actual) {
  return copy_info(value, std::strlen(value) + 1, size, out, actual);
}
bool cpu_device(cl_device_id device) {
  cl_device_type type = 0;
  return REAL(clGetDeviceInfo)(device, CL_DEVICE_TYPE, sizeof(type), &type,
                               nullptr) == CL_SUCCESS &&
         (type & CL_DEVICE_TYPE_CPU);
}
bool valid_device_type(cl_device_type type) {
  constexpr cl_device_type allowed = CL_DEVICE_TYPE_DEFAULT | CL_DEVICE_TYPE_CPU |
                                    CL_DEVICE_TYPE_GPU | CL_DEVICE_TYPE_ACCELERATOR |
                                    CL_DEVICE_TYPE_CUSTOM;
  return type == CL_DEVICE_TYPE_ALL || (type && !(type & ~allowed));
}
cl_device_type backing_device_type(cl_device_type type) {
  if (type == CL_DEVICE_TYPE_ALL)
    return type;
  const bool gpu = type & CL_DEVICE_TYPE_GPU;
  type &= ~(CL_DEVICE_TYPE_CPU | CL_DEVICE_TYPE_GPU);
  if (gpu)
    type |= CL_DEVICE_TYPE_CPU;
  // No accelerator ICD is installed; this preserves validation in the loader
  // while yielding NOT_FOUND for a request for the hidden CPU device alone.
  return type ? type : CL_DEVICE_TYPE_ACCELERATOR;
}
