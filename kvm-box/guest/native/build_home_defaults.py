#!/usr/bin/env python3
"""Compile pinned, public desktop defaults into an immutable C data header.

The input is a pristine extracted image home, never a running user's home.
Only the exact manifest tree is accepted; no Sunshine state or credentials.
Runtime authentication still depends on admitting the image/nsinit artifact.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import stat

HERE = Path(__file__).resolve().parent


def path_parts(value):
    if not isinstance(value, str) or len(value.encode()) > 255:
        raise ValueError('invalid manifest path')
    parts = value.split('/')
    if not 1 <= len(parts) <= 8 or any(
        not x or x in ('.', '..') or len(x.encode()) > 64 or
        any(not c.isascii() or not (c.isalnum() or c in '._-') for c in x)
        for x in parts
    ):
        raise ValueError('invalid manifest path')
    return parts


def source_root(path):
    """Pin every input component without following links."""
    absolute = os.path.abspath(path)
    fd = os.open('/', os.O_RDONLY | os.O_DIRECTORY | os.O_CLOEXEC)
    try:
        for part in Path(absolute).parts[1:]:
            child = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=fd)
            os.close(fd)
            fd = child
        return fd
    except BaseException:
        os.close(fd)
        raise


def collect(root, wanted_files, wanted_dirs):
    found = {}
    seen_dirs = set()

    def visit(fd, prefix):
        for name in sorted(os.listdir(fd)):
            relative = f'{prefix}/{name}' if prefix else name
            st = os.stat(name, dir_fd=fd, follow_symlinks=False)
            if stat.S_ISDIR(st.st_mode):
                if relative not in wanted_dirs:
                    raise ValueError(f'unexpected directory: {relative}')
                child = os.open(name, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=fd)
                try:
                    seen_dirs.add(relative)
                    visit(child, relative)
                finally:
                    os.close(child)
            elif stat.S_ISREG(st.st_mode):
                if relative not in wanted_files:
                    raise ValueError(f'unexpected file: {relative}')
                expected = wanted_files[relative]
                f = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC, dir_fd=fd)
                with os.fdopen(f, 'rb') as stream:
                    actual = os.fstat(stream.fileno())
                    if not stat.S_ISREG(actual.st_mode) or actual.st_nlink != 1 or actual.st_size != expected['bytes']:
                        raise ValueError(f'file type/size/link mismatch: {relative}')
                    data = stream.read(expected['bytes'] + 1)
                if len(data) != expected['bytes'] or hashlib.sha256(data).hexdigest() != expected['sha256']:
                    raise ValueError(f'content mismatch: {relative}')
                found[relative] = data
            else:
                raise ValueError(f'nonregular entry: {relative}')

    visit(root, '')
    if set(found) != set(wanted_files) or seen_dirs != wanted_dirs:
        raise ValueError('missing manifest entries')
    return found


def build(root_path, manifest_path):
    manifest = json.loads(Path(manifest_path).read_text())
    if manifest.get('schema') != 'kvm-box-native-home-defaults/1':
        raise ValueError('invalid manifest schema')
    entries = manifest['files']
    if not 1 <= len(entries) <= 128:
        raise ValueError('invalid file count')
    files = {}
    dirs = set()
    total = 0
    for entry in entries:
        name = entry['path']
        parts = path_parts(name)
        if name in files or type(entry['bytes']) is not int or not 0 <= entry['bytes'] <= 262144 or entry['mode'] != 0o644:
            raise ValueError('invalid file metadata')
        digest = entry['sha256']
        if not isinstance(digest, str) or len(digest) != 64 or any(c not in '0123456789abcdef' for c in digest):
            raise ValueError('invalid file digest')
        files[name] = entry
        dirs.update('/'.join(parts[:i]) for i in range(1, len(parts)))
        total += entry['bytes']
    if len(dirs) > 64 or total > 1048576 or set(files) & dirs:
        raise ValueError('invalid tree bounds')
    root = source_root(root_path)
    try:
        data = collect(root, files, dirs)
    finally:
        os.close(root)
    digest = hashlib.sha256(json.dumps(manifest, sort_keys=True, separators=(',', ':'), ensure_ascii=True).encode()).hexdigest()
    out = ['/* Generated by build_home_defaults.py; edit pinned inputs, not this file. */',
           '#ifndef KVMBOX_HOME_DEFAULTS_H', '#define KVMBOX_HOME_DEFAULTS_H',
           '#include <stddef.h>', '#include <sys/types.h>',
           'struct native_home_file { const char *path; const unsigned char *data; size_t size; mode_t mode; };',
           f'#define NATIVE_HOME_MANIFEST_SHA256 "{digest}"',
           'static const char *const native_home_dirs[] = {']
    out.extend(f'    {json.dumps(d)},' for d in sorted(dirs, key=lambda x: (x.count('/'), x)))
    out.append('};')
    for i, name in enumerate(sorted(files)):
        out.append(f'static const unsigned char native_home_data_{i}[] = {{')
        b = data[name]
        for offset in range(0, len(b), 16):
            out.append('    ' + ','.join(f'0x{x:02x}' for x in b[offset:offset + 16]) + ',')
        if not b:
            out.append('    0,')
        out.append('};')
    out.append('static const struct native_home_file native_home_files[] = {')
    for i, name in enumerate(sorted(files)):
        out.append(f'    {{{json.dumps(name)}, native_home_data_{i}, {len(data[name])}, 0644}},')
    out.extend(['};', '#endif', ''])
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', required=True, type=Path)
    parser.add_argument('--manifest', type=Path, default=HERE / 'home-defaults-manifest.json')
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    # Validate the complete input before creating/replacing any generated file.
    result = build(args.root, args.manifest)
    args.output.write_text(result)


if __name__ == '__main__':
    main()
